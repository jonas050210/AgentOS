import { ModelInfo, ProviderInfo } from '../../shared/types.js';
import { GenerateRequest, GenerateResponse, ModelProvider } from './types.js';

/**
 * Deterministic offline provider. It is always available and is used so the
 * application remains fully functional (and testable) without any external
 * model, credentials or network access. It performs no reasoning beyond
 * routing acknowledgement, and clearly labels its output as such.
 */
export class EchoProvider implements ModelProvider {
  readonly id = 'builtin';
  readonly name = 'Built-in offline assistant';
  readonly type = 'local' as const;

  info(): ProviderInfo {
    return {
      id: this.id,
      name: this.name,
      type: this.type,
      available: true,
      configured: true,
      detail: 'No external dependency — deterministic local fallback',
    };
  }

  async isAvailable(): Promise<boolean> {
    return true;
  }

  async listModels(): Promise<ModelInfo[]> {
    return [
      {
        id: `${this.id}:offline-reasoner`,
        name: 'offline-reasoner',
        providerId: this.id,
        capability: ['chat', 'general', 'planning'],
        status: 'available',
        detail: 'Rule-based local engine (no LLM weights)',
      },
    ];
  }

  async generate(req: GenerateRequest): Promise<GenerateResponse> {
    const model = req.model || 'offline-reasoner';
    const system = (req.system || '').trim();
    const prompt = req.prompt.trim();
    const lines = [
      `[offline engine] I received your request (${prompt.length} characters).`,
      '',
      system ? `Active system directive: ${system.split('\n')[0]}` : '',
      'No external model provider is configured, so this response is generated by',
      'AgentOS\'s deterministic local fallback. It does not perform real language',
      'reasoning. Configure a provider in Settings → Providers to enable real inference.',
    ].filter(Boolean);
    return { text: lines.join('\n'), model, providerId: this.id };
  }
}
